#!/usr/bin/env bash
# Write each explorer theme's per-basin query, <t>.sql, from its all-basins query,
# <t>-all.sql: the same SQL filtered to the selected basin ({{ID}}), so a live per-basin run
# returns exactly the precomputed rows. Run after editing any <t>-all.sql.
set -euo pipefail
cd "$(dirname "$0")/../explorer/config/themes"
for all in */*-all.sql; do
    t=$(basename "$all" -all.sql)
    out="$(dirname "$all")/$t.sql"
    {
        echo "-- ${t^} for one basin (the selected unit, {{ID}}) at one level ({{LEVEL}})."
        echo "-- Generated by scripts/build-explorer-sql.sh from $t-all.sql, filtered to one basin, so its"
        echo "-- numbers are identical to the all-basins rows by construction. Scores need every basin, so a"
        echo "-- live run costs as much as the all-basins query; the app reads precomputed rows."
        echo "SELECT * EXCLUDE (id) FROM ("
        cat "$all"
        echo ") WHERE id = {{ID}}"
    } > "$out"
done
